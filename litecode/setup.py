"""First-run setup wizard: detect hardware, recommend a model set that fits,
ask permission, let the user choose, download, write config, verify.
"""
from __future__ import annotations
import os, sys, time, urllib.request
from pathlib import Path
from . import doctor, catalog, config


def _fmt(m: catalog.Model) -> str:
    tag = "  [security-permissive, official]" if m.official_permissive else ""
    return f"{m.name:<26} {m.size_gb:4.1f} GB dl / ~{m.ram_gb:3.1f} GB RAM   {m.note}{tag}"


def _ask(prompt: str, default: str = "y") -> bool:
    try:
        ans = input(f"{prompt} [{'Y/n' if default=='y' else 'y/N'}] ").strip().lower()
    except EOFError:
        return default == "y"
    if not ans:
        return default == "y"
    return ans.startswith("y")


def _download(url: str, dest: Path):
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(dest.suffix + ".part")
    have = tmp.stat().st_size if tmp.exists() else 0
    req = urllib.request.Request(url)
    if have:
        req.add_header("Range", f"bytes={have}-")
    with urllib.request.urlopen(req, timeout=60) as r:
        total = int(r.headers.get("Content-Length", 0)) + have
        mode = "ab" if have else "wb"
        done = have; t0 = time.time(); last = 0
        with open(tmp, mode) as f:
            while True:
                chunk = r.read(1 << 20)
                if not chunk:
                    break
                f.write(chunk); done += len(chunk)
                if time.time() - last > 0.5:
                    spd = (done - have) / max(1e-6, time.time() - t0) / 1e6
                    pct = f"{done/total*100:4.1f}%" if total else f"{done/1e6:.0f}MB"
                    sys.stdout.write(f"\r    {dest.name}: {pct}  {spd:5.1f} MB/s   ")
                    sys.stdout.flush(); last = time.time()
    tmp.rename(dest)
    sys.stdout.write(f"\r    {dest.name}: done ({dest.stat().st_size/1e9:.2f} GB)        \n")


def run():
    cfg = config.load()
    print("litecode setup")
    print("=" * 60)
    env = doctor.detect()
    print(env.summary())
    print("=" * 60)

    budget = env.ram_budget_gb
    want_sec = _ask("Install a security-permissive model for authorized pentest / CTF work?", "y")
    rec = catalog.recommend(budget, want_security=want_sec)

    print(f"\nRecommended model set for ~{budget:.0f} GB RAM budget:\n")
    seen = {}
    for role, m in rec.items():
        seen.setdefault(m.key, []).append(role)
    for key, roles in seen.items():
        m = catalog.BY_KEY[key]
        print(f"  [{','.join(roles):<14}] {_fmt(m)}")
    total_dl = sum(catalog.BY_KEY[k].size_gb for k in seen)
    print(f"\n  Total download: ~{total_dl:.1f} GB into {cfg['models_dir']}")

    best_disk = max(env.disks, key=lambda d: d.free_gb, default=None)
    if best_disk and best_disk.free_gb < total_dl + 2:
        print(f"  WARNING: largest free disk {best_disk.mount} has only {best_disk.free_gb:.0f} GB.")

    if not _ask("\nProceed to download these models?", "y"):
        print("Cancelled. You can edit choices in ~/.litecode/config.toml and re-run `litecode setup`.")
        return

    models_dir = Path(cfg["models_dir"])
    chosen = {}
    for key, roles in seen.items():
        m = catalog.BY_KEY[key]
        dest = models_dir / m.file
        if dest.exists():
            print(f"  have {m.file}")
        else:
            print(f"  downloading {m.name} ...")
            try:
                _download(m.url, dest)
            except Exception as e:
                print(f"    FAILED: {e}  (you can re-run setup to resume)")
                continue
        for r in roles:
            chosen[r] = m.file

    _write_config(cfg, chosen)
    print("\nSetup complete. Models and roles written to ~/.litecode/config.toml")
    print("Run `litecode` in any project folder to start.")


def _write_config(cfg: dict, roles: dict):
    home = config.HOME
    home.mkdir(parents=True, exist_ok=True)
    lines = [
        "# litecode config (generated by `litecode setup`)",
        f'models_dir = "{cfg["models_dir"]}"',
        f'engine = "{cfg["engine"]}"',
        f'threads = {cfg["threads"]}',
        f'ctx = {cfg["ctx"]}',
        "",
        "[roles]",
    ]
    for r, fn in roles.items():
        lines.append(f'{r} = "{fn}"')
    (home / "config.toml").write_text("\n".join(lines) + "\n", encoding="utf-8")
